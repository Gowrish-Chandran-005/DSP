def extract_one_video(path, metadata_row, landmarker):
    record = {
        "filename": metadata_row["filename"],
        "participant": metadata_row.get("participant"),
        "label": metadata_row.get("label"),
        "agreement_ratio": metadata_row.get("agreement_ratio"),
        "gender": metadata_row.get("gender"),
        "duration": metadata_row.get("duration"),
        "sampled_frames": 0,
        "successful_reads": 0,
        "face_frames": 0,
        "face_detection_rate": np.nan,
        "processing_error": ""
    }

    cap = cv2.VideoCapture(path)

    if not cap.isOpened():
        record["processing_error"] = "OpenCV could not open video"
        return record

    try:
        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

        if total_frames <= 0:
            record["processing_error"] = "No frames reported"
            return record

        indices = np.linspace(
            0, total_frames - 1,
            num=min(MAX_FRAMES, total_frames),
            dtype=int
        )

        record["sampled_frames"] = len(indices)

        blendshape_frames = []

        for idx in indices:
            cap.set(cv2.CAP_PROP_POS_FRAMES, int(idx))
            ok, frame = cap.read()

            if not ok or frame is None:
                continue

            record["successful_reads"] += 1

            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            mp_image = mp.Image(
                image_format=mp.ImageFormat.SRGB,
                data=np.ascontiguousarray(rgb)
            )

            result = landmarker.detect(mp_image)

            if not result.face_landmarks:
                continue

            record["face_frames"] += 1

            if result.face_blendshapes:
                scores = {
                    item.category_name: item.score
                    for item in result.face_blendshapes[0]
                }
                blendshape_frames.append(scores)

        if record["sampled_frames"] > 0:
            record["face_detection_rate"] = (
                record["face_frames"] / record["sampled_frames"]
            )

        if blendshape_frames:
            score_df = pd.DataFrame(blendshape_frames)

            for col in score_df.columns:
                record[f"blend_{col}_mean"] = score_df[col].mean()
                record[f"blend_{col}_std"] = score_df[col].std(ddof=0)

        if record["successful_reads"] == 0:
            record["processing_error"] = "All sampled frame reads failed"

    except Exception as e:
        record["processing_error"] = f"{type(e).__name__}: {e}"

    finally:
        cap.release()

    return record

