def summarize_video(video_path, landmarker):
    cap = cv2.VideoCapture(video_path)

    if not cap.isOpened():
        return {
            "processing_error": "cannot_open_video",
            "video_duration_seconds": np.nan,
            "sampled_frames": 0,
            "face_frames": 0,
            "face_detection_rate": 0.0
        }

    fps = cap.get(cv2.CAP_PROP_FPS)
    frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    duration = (
        frame_count / fps
        if fps and np.isfinite(fps) and fps > 0
        else np.nan
    )

    if frame_count <= 0:
        cap.release()
        return {
            "processing_error": "empty_video",
            "video_duration_seconds": duration,
            "sampled_frames": 0,
            "face_frames": 0,
            "face_detection_rate": 0.0
        }

    n = min(MAX_FRAMES_PER_VIDEO, frame_count)
    indices = np.unique(
        np.linspace(0, frame_count - 1, n, dtype=int)
    )

    scores_by_name = {}
    detected = 0
    sampled = 0
    last_timestamp_ms = -1
    frame_errors = 0

    for idx in indices:
        cap.set(cv2.CAP_PROP_POS_FRAMES, int(idx))
        ok, frame = cap.read()

        if not ok:
            frame_errors += 1
            continue

        # Timestamp must strictly increase within each video.
        if fps and np.isfinite(fps) and fps > 0:
            timestamp_ms = int(round(idx * 1000.0 / fps))
        else:
            timestamp_ms = (last_timestamp_ms + 1000)

        timestamp_ms = max(timestamp_ms, last_timestamp_ms + 1)
        last_timestamp_ms = timestamp_ms

        try:
            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            image = mp.Image(
                image_format=mp.ImageFormat.SRGB,
                data=rgb
            )

            result = landmarker.detect_for_video(
                image, timestamp_ms
            )
            sampled += 1

            if not result.face_blendshapes:
                continue

            detected += 1

            for category in result.face_blendshapes[0]:
                name = category.category_name
                scores_by_name.setdefault(name, []).append(
                    float(category.score)
                )

        except Exception as e:
            frame_errors += 1
            print(
                f"Frame error in {os.path.basename(video_path)} "
                f"at frame {idx}: {str(e)[:120]}"
            )

    cap.release()

    features = {
        "video_duration_seconds": float(duration)
            if np.isfinite(duration) else np.nan,
        "sampled_frames": int(sampled),
        "face_frames": int(detected),
        "face_detection_rate": (
            float(detected / sampled) if sampled else 0.0
        ),
        "frame_errors": int(frame_errors),
        "processing_error": ""
    }

    for name, values in scores_by_name.items():
        values = np.asarray(values, dtype=float)
        features[f"blend_{name}_mean"] = float(values.mean())
        features[f"blend_{name}_std"] = float(values.std())

    return features


