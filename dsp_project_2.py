def save_batch(rows):
    if not rows:
        return

    batch = pd.DataFrame(rows)

    # Keep a consistent column layout when resuming.
    if os.path.exists(OUTPUT_CSV):
        old_cols = list(pd.read_csv(OUTPUT_CSV, nrows=0).columns)

        for col in old_cols:
            if col not in batch.columns:
                batch[col] = np.nan

        for col in batch.columns:
            if col not in old_cols:
                # New columns can occur if an existing partial CSV
                # was created with a different extractor version.
                old_cols.append(col)

        batch = batch.reindex(columns=old_cols)

        # If the schema changed, rewrite the file consistently.
        current_cols = list(pd.read_csv(OUTPUT_CSV, nrows=0).columns)
        if current_cols != old_cols:
            old = pd.read_csv(OUTPUT_CSV)
            old = old.reindex(columns=old_cols)
            batch = batch.reindex(columns=old_cols)
            pd.concat([old, batch], ignore_index=True).to_csv(
                OUTPUT_CSV, index=False
            )
        else:
            batch.to_csv(
                OUTPUT_CSV, mode="a", header=False, index=False
            )
    else:
        batch.to_csv(OUTPUT_CSV, index=False)


